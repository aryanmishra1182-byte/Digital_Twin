import React, { useState } from 'react';
import {
  AlertTriangle,
  CheckCircle,
  Clock,
  ShieldAlert,
  Info,
  CheckSquare,
  Wrench,
  Filter,
  RefreshCw,
  X,
  MessageSquare,
  ArrowRight
} from 'lucide-react';
import { AlertRecord, AlertStatus, AlertSeverity } from '../types';
import { api } from '../api/client';
import { SeverityBadge, StatusBadge } from '../components/ui/Badge';
import { SectionHeader } from '../components/ui/SectionHeader';

interface AlertsMaintenanceProps {
  alerts: AlertRecord[];
  onRefresh: () => void;
}

export const AlertsMaintenance: React.FC<AlertsMaintenanceProps> = ({ alerts, onRefresh }) => {
  const [filterStatus, setFilterStatus] = useState<string>('ALL');
  const [selectedAlert, setSelectedAlert] = useState<AlertRecord | null>(null);
  const [actionType, setActionType] = useState<'ACKNOWLEDGE' | 'RESOLVE' | null>(null);
  const [operatorNote, setOperatorNote] = useState('');
  const [submitting, setSubmitting] = useState(false);

  const filteredAlerts = alerts.filter((a) => {
    if (filterStatus === 'ALL') return true;
    return a.status === filterStatus;
  });

  const activeCount = alerts.filter((a) => a.status === 'ACTIVE').length;
  const ackCount = alerts.filter((a) => a.status === 'ACKNOWLEDGED').length;
  const resolvedCount = alerts.filter((a) => a.status === 'RESOLVED').length;

  const handleActionSubmit = async () => {
    if (!selectedAlert || !actionType) return;
    setSubmitting(true);
    try {
      if (actionType === 'ACKNOWLEDGE') {
        await api.acknowledgeAlert(selectedAlert.id, operatorNote);
      } else {
        await api.resolveAlert(selectedAlert.id, operatorNote);
      }
      setSelectedAlert(null);
      setActionType(null);
      setOperatorNote('');
      onRefresh();
    } catch (e) {
      alert('Failed to update alert: ' + e);
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <SectionHeader
        title="Industrial Maintenance & Alert Queue"
        subtitle="Hysteresis-buffered event dispatches generated by anomaly detection and fault classification models."
        tag="Operator Workbench"
        actions={
          <button
            onClick={onRefresh}
            className="px-3 py-1.5 rounded border border-rule bg-panel hover:bg-track text-ink font-medium text-xs inline-flex items-center gap-1.5 transition-colors cursor-pointer"
          >
            <RefreshCw className="w-3.5 h-3.5 text-mute" />
            <span>Refresh Queue</span>
          </button>
        }
      />

      {/* Alert KPI Summary Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        <div className="bg-panel border border-rule rounded p-4 flex items-center justify-between">
          <div>
            <span className="text-xs font-mono uppercase tracking-wider text-mute block">Active Critical/Warning</span>
            <span className="text-2xl font-serif text-ink font-normal mt-1 block">{activeCount}</span>
            <span className="text-[11px] text-mute">Requires operator attention</span>
          </div>
          <div className="w-10 h-10 rounded border border-rose-300 bg-rose-50 text-rose-700 flex items-center justify-center">
            <ShieldAlert className="w-5 h-5" />
          </div>
        </div>

        <div className="bg-panel border border-rule rounded p-4 flex items-center justify-between">
          <div>
            <span className="text-xs font-mono uppercase tracking-wider text-mute block">Acknowledged</span>
            <span className="text-2xl font-serif text-ink font-normal mt-1 block">{ackCount}</span>
            <span className="text-[11px] text-mute">Assigned to maintenance technician</span>
          </div>
          <div className="w-10 h-10 rounded border border-amber-300 bg-amber-50 text-amber-700 flex items-center justify-center">
            <Clock className="w-5 h-5" />
          </div>
        </div>

        <div className="bg-panel border border-rule rounded p-4 flex items-center justify-between">
          <div>
            <span className="text-xs font-mono uppercase tracking-wider text-mute block">Resolved This Cycle</span>
            <span className="text-2xl font-serif text-ink font-normal mt-1 block">{resolvedCount}</span>
            <span className="text-[11px] text-mute">Verified healthy return to service</span>
          </div>
          <div className="w-10 h-10 rounded border border-emerald-300 bg-emerald-50 text-emerald-700 flex items-center justify-center">
            <CheckCircle className="w-5 h-5" />
          </div>
        </div>
      </div>

      {/* Filter Bar */}
      <div className="flex flex-wrap items-center justify-between gap-3 bg-panel border border-rule rounded p-3 text-xs">
        <div className="flex items-center gap-2">
          <Filter className="w-3.5 h-3.5 text-mute" />
          <span className="font-mono uppercase text-mute">Filter Queue:</span>
          {(['ALL', 'ACTIVE', 'ACKNOWLEDGED', 'RESOLVED'] as const).map((status) => (
            <button
              key={status}
              onClick={() => setFilterStatus(status)}
              className={`px-2.5 py-1 rounded text-xs font-mono transition-colors cursor-pointer ${
                filterStatus === status
                  ? 'bg-ink text-bg font-medium'
                  : 'bg-bg text-mute hover:text-ink border border-rule'
              }`}
            >
              {status}
            </button>
          ))}
        </div>
        <div className="text-mute font-mono text-[11px]">
          Showing {filteredAlerts.length} of {alerts.length} events (Hysteresis suppression enabled)
        </div>
      </div>

      {/* Alerts Table */}
      <div className="border border-rule rounded bg-panel overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs font-sans">
            <thead>
              <tr className="border-b border-rule bg-bg/50 text-mute uppercase font-mono text-[10px]">
                <th className="py-3 px-4">Severity</th>
                <th className="py-3 px-4">Motor ID</th>
                <th className="py-3 px-4">Fault Indication</th>
                <th className="py-3 px-4">Event Summary</th>
                <th className="py-3 px-4">Timestamp</th>
                <th className="py-3 px-4">Status</th>
                <th className="py-3 px-4 text-right">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-rule/60">
              {filteredAlerts.length === 0 ? (
                <tr>
                  <td colSpan={7} className="py-8 text-center text-mute font-sans">
                    No alerts match the selected status filter. Motor operation nominal.
                  </td>
                </tr>
              ) : (
                filteredAlerts.map((alert) => (
                  <tr key={alert.id} className="hover:bg-track/50 transition-colors">
                    <td className="py-3 px-4 whitespace-nowrap">
                      <SeverityBadge severity={alert.severity} />
                    </td>
                    <td className="py-3 px-4 font-mono font-medium text-ink whitespace-nowrap">
                      {alert.motorId}
                    </td>
                    <td className="py-3 px-4 font-mono text-[11px] text-ink whitespace-nowrap">
                      {alert.faultClass}
                    </td>
                    <td className="py-3 px-4 text-ink max-w-md truncate">
                      {alert.title}
                    </td>
                    <td className="py-3 px-4 font-mono text-[11px] text-mute whitespace-nowrap">
                      {new Date(alert.timestamp).toLocaleTimeString()}
                    </td>
                    <td className="py-3 px-4 whitespace-nowrap">
                      <StatusBadge status={alert.status} />
                    </td>
                    <td className="py-3 px-4 text-right whitespace-nowrap">
                      <div className="inline-flex items-center gap-1.5">
                        <button
                          onClick={() => {
                            setSelectedAlert(alert);
                            setActionType(null);
                          }}
                          className="px-2 py-1 rounded border border-rule hover:bg-track text-ink text-[11px] font-mono transition-colors cursor-pointer"
                        >
                          Inspect
                        </button>
                        {alert.status === 'ACTIVE' && (
                          <button
                            onClick={() => {
                              setSelectedAlert(alert);
                              setActionType('ACKNOWLEDGE');
                            }}
                            className="px-2 py-1 rounded bg-amber-500/15 border border-amber-500/30 text-amber-700 hover:bg-amber-500/25 text-[11px] font-mono transition-colors cursor-pointer"
                          >
                            Ack
                          </button>
                        )}
                        {alert.status === 'ACKNOWLEDGED' && (
                          <button
                            onClick={() => {
                              setSelectedAlert(alert);
                              setActionType('RESOLVE');
                            }}
                            className="px-2 py-1 rounded bg-emerald-500/15 border border-emerald-500/30 text-emerald-700 hover:bg-emerald-500/25 text-[11px] font-mono transition-colors cursor-pointer"
                          >
                            Resolve
                          </button>
                        )}
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Modal / Slide-Over for Inspection & Actions */}
      {selectedAlert && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-ink/40 backdrop-blur-sm animate-fade-in">
          <div className="bg-panel border border-rule rounded-lg max-w-lg w-full p-6 shadow-xl relative max-h-[90vh] overflow-y-auto">
            <button
              onClick={() => {
                setSelectedAlert(null);
                setActionType(null);
              }}
              className="absolute right-4 top-4 text-mute hover:text-ink cursor-pointer"
            >
              <X className="w-4 h-4" />
            </button>

            <div className="flex items-center gap-2 mb-3">
              <SeverityBadge severity={selectedAlert.severity} />
              <StatusBadge status={selectedAlert.status} />
              <span className="text-xs font-mono text-mute">{selectedAlert.motorId}</span>
            </div>

            <h3 className="text-lg font-serif text-ink font-normal">{selectedAlert.title}</h3>
            <p className="text-xs text-mute mt-2 leading-relaxed font-sans">{selectedAlert.description}</p>

            <div className="mt-4 p-3 rounded bg-bg border border-rule space-y-1.5 text-xs font-mono">
              <div className="flex justify-between">
                <span className="text-mute">Dispatched Time:</span>
                <span className="text-ink">{new Date(selectedAlert.timestamp).toLocaleString()}</span>
              </div>
              <div className="flex justify-between">
                <span className="text-mute">Target Fault Mode:</span>
                <span className="text-ink">{selectedAlert.faultClass}</span>
              </div>
              {selectedAlert.operatorNote && (
                <div className="pt-2 border-t border-rule mt-2">
                  <span className="text-mute block mb-0.5">Operator Notes:</span>
                  <span className="text-ink font-sans text-xs italic">{selectedAlert.operatorNote}</span>
                </div>
              )}
            </div>

            {actionType ? (
              <div className="mt-5 space-y-3 pt-4 border-t border-rule">
                <label className="block text-xs font-mono uppercase tracking-wider text-mute">
                  {actionType === 'ACKNOWLEDGE' ? 'Acknowledge Event & Add Note' : 'Resolve Event & Close Ticket'}
                </label>
                <textarea
                  value={operatorNote}
                  onChange={(e) => setOperatorNote(e.target.value)}
                  placeholder={
                    actionType === 'ACKNOWLEDGE'
                      ? 'e.g. Assigned to technician. Dispatched for MCSA sideband check.'
                      : 'e.g. Rotor bearing replaced, motor re-lubricated. Normal baseline confirmed.'
                  }
                  className="w-full p-2.5 text-xs bg-bg border border-rule rounded text-ink focus:outline-none focus:border-ink resize-none h-20 font-sans"
                />
                <div className="flex justify-end gap-2">
                  <button
                    onClick={() => setActionType(null)}
                    className="px-3 py-1.5 rounded border border-rule text-xs hover:bg-track font-medium text-mute"
                  >
                    Cancel
                  </button>
                  <button
                    onClick={handleActionSubmit}
                    disabled={submitting}
                    className="px-4 py-1.5 rounded bg-ink text-bg text-xs font-medium hover:bg-ink/90 transition-colors disabled:opacity-50"
                  >
                    {submitting ? 'Submitting...' : 'Confirm Action'}
                  </button>
                </div>
              </div>
            ) : (
              <div className="mt-6 flex justify-end gap-2 pt-4 border-t border-rule">
                {selectedAlert.status === 'ACTIVE' && (
                  <button
                    onClick={() => setActionType('ACKNOWLEDGE')}
                    className="px-4 py-2 rounded bg-amber-500/15 border border-amber-500/30 text-amber-700 hover:bg-amber-500/25 text-xs font-medium transition-colors"
                  >
                    Acknowledge Alert
                  </button>
                )}
                {selectedAlert.status === 'ACKNOWLEDGED' && (
                  <button
                    onClick={() => setActionType('RESOLVE')}
                    className="px-4 py-2 rounded bg-emerald-500/15 border border-emerald-500/30 text-emerald-700 hover:bg-emerald-500/25 text-xs font-medium transition-colors"
                  >
                    Resolve Alert
                  </button>
                )}
                <button
                  onClick={() => setSelectedAlert(null)}
                  className="px-4 py-2 rounded border border-rule hover:bg-track text-ink text-xs font-medium transition-colors"
                >
                  Close
                </button>
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
};
